/**
 * Exports the Supabase Cloud project's data as SQL for the self-hosted
 * stack. Reads through the Management API, so it needs no database
 * password — only SUPABASE_ACCESS_TOKEN from .env.local.
 *
 * Deliberately narrow: this project's data is small, and copying the
 * tables the app actually owns is easier to verify than a full pg_dump.
 * Passwords come across as bcrypt hashes in auth.users.encrypted_password,
 * which is why nobody has to reset one.
 *
 * Usage:  node ops/supabase/export-cloud-data.mjs > migration.sql
 */
import { readFileSync } from "fs";
import { resolve } from "path";

const PROJECT = process.env.SUPABASE_PROJECT_REF ?? "mmvpbomvmgbceqmjwrpv";

for (const line of readFileSync(resolve(process.cwd(), ".env.local"), "utf8").split("\n")) {
  const m = line.match(/^([^#=]+)=(.*)$/);
  if (m) process.env[m[1].trim()] ??= m[2].trim();
}
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN;
if (!TOKEN) throw new Error("SUPABASE_ACCESS_TOKEN missing from .env.local");

async function query(sql) {
  const res = await fetch(
    `https://api.supabase.com/v1/projects/${PROJECT}/database/query`,
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${TOKEN}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ query: sql }),
    },
  );
  if (!res.ok) throw new Error(`${res.status}: ${(await res.text()).slice(0, 300)}`);
  return res.json();
}

/** JSON value → SQL literal. */
function lit(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

/**
 * `confirmed_at` (auth.users) and `email` (auth.identities) are generated
 * columns — inserting them errors. Everything else travels.
 */
const TABLES = [
  { name: "auth.users", skip: ["confirmed_at"] },
  { name: "auth.identities", skip: ["email"] },
  { name: "public.profiles" },
  { name: "public.agents" },
  { name: "public.rooms" },
  { name: "public.room_members" },
  { name: "public.assignments" },
  { name: "public.messages" },
  // audit_logs.id is `generated always as identity` — an explicit value is
  // rejected. Nothing references it, so let Postgres assign new ones.
  { name: "public.audit_logs", skip: ["id"] },
];

const out = [];
out.push("-- Generated by ops/supabase/export-cloud-data.mjs");
out.push(`-- Source project: ${PROJECT}   Generated: ${new Date().toISOString()}`);
out.push("-- Apply with:  psql -v ON_ERROR_STOP=1 -f migration.sql");
out.push("begin;");
out.push("set session_replication_role = replica;  -- do not fire triggers\n");

const summary = [];
for (const { name, skip = [] } of TABLES) {
  const [schema, table] = name.split(".");
  const cols = (
    await query(
      `select column_name from information_schema.columns
        where table_schema='${schema}' and table_name='${table}'
        order by ordinal_position`,
    )
  )
    .map((r) => r.column_name)
    .filter((c) => !skip.includes(c));

  const rows = await query(
    `select ${cols.map((c) => `"${c}"`).join(", ")} from ${name}`,
  );
  summary.push(`${name}: ${rows.length}`);

  out.push(`-- ${name} (${rows.length} rows)`);
  // audit_logs travels without its generated id, so `on conflict do
  // nothing` has nothing to match and a re-run would duplicate every row.
  // It is a full snapshot each time, so replace it wholesale.
  if (name === "public.audit_logs") out.push("delete from public.audit_logs;");
  for (const row of rows) {
    const values = cols.map((c) => lit(row[c])).join(", ");
    out.push(
      `insert into ${name} (${cols.map((c) => `"${c}"`).join(", ")}) ` +
        `values (${values}) on conflict do nothing;`,
    );
  }
  out.push("");
}

out.push("set session_replication_role = origin;");
out.push("commit;");
out.push("");
out.push("-- Row counts at export time:");
for (const s of summary) out.push(`--   ${s}`);

process.stdout.write(out.join("\n"));
process.stderr.write(`exported ${summary.join(", ")}\n`);
